  root.style.setProperty('--bg-mid', theme.bgMid);
  root.style.setProperty('--bg-top', theme.bgTop);
  root.style.setProperty('--card-top', theme.cardTop);
  root.style.setProperty('--card-mid', theme.cardMid);
  root.style.setProperty('--card-bottom', theme.cardBottom);
  root.style.setProperty('--surface-deep', theme.surfaceDeep);
  root.style.setProperty('--header-bg', theme.headerBg);
  root.style.setProperty('--accent', theme.accent);
  root.style.setProperty('--accent-rgb', theme.accentRgb);
  root.style.setProperty('--secondary', theme.secondary);
  root.style.setProperty('--secondary-rgb', theme.secondaryRgb);
  root.style.setProperty('--silver', theme.silver);
  root.style.setProperty('--silver-muted', theme.silverMuted);
  root.style.setProperty('--text-primary', theme.textPrimary);
  root.style.setProperty('--text-body', theme.textBody);
  root.style.setProperty('--text-muted', theme.textMuted);
